"""Run real Android sh state/boot-latch tests in a disposable isolated fixture."""
from pathlib import Path
import argparse,json,shlex,subprocess,tempfile
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--adb',default='adb');p.add_argument('--serial');a=p.parse_args()
 adb=[a.adb]+(['-s',a.serial] if a.serial else [])
 fixture='/data/local/tmp/rk-mali-ui-test068';current=fixture+'/modules/rk3588_mali_global';staged=fixture+'/modules_update/rk3588_mali_global';state=fixture+'/state'
 def shell(s):return subprocess.run(adb+['shell',s],capture_output=True,text=True,encoding='utf-8',errors='replace',check=True).stdout
 def put(path,text):
  with tempfile.NamedTemporaryFile(delete=False) as f:f.write(text.encode());local=Path(f.name)
  try:
   subprocess.run(adb+['push',str(local),path],check=True,capture_output=True)
  finally:local.unlink()
 checks=0
 def expect(v,message):
  nonlocal checks
  assert v,message;checks+=1
 def invoke(*args):return json.loads(shell('sh '+current+'/webui.sh '+' '.join(shlex.quote(x) for x in args)))
 shell('test ! -e '+fixture+' && mkdir -p '+current+' '+staged+' '+state)
 try:
  for name in ['kernel-state.sh','cold-state.sh','dvfs-state.sh','fence-state.sh','dvfs-boot.sh','mode-control.sh','webui.sh','module.prop']:
   text=(ROOT/'magisk-mali-global'/name).read_text(encoding='utf-8')
   text=text.replace('/data/adb/modules_update',fixture+'/modules_update').replace('/data/adb/modules',fixture+'/modules').replace('/data/adb/rk3588-mali-global',state)
   text=text.replace('/sys/class/devfreq/fb000000.gpu',fixture+'/devfreq').replace('/sys/module/rk_mali_next/parameters/csf_fence_safe',state+'/fence-actual')
   if name=='kernel-state.sh':text+='\nkernel_supported(){ [ "$(cat '+state+'/supported)" = yes ]; }\nkernel_active(){ cat '+state+'/actual-kernel; }\n'
   put(current+'/'+name,text)
  put(state+'/supported','yes\n');put(state+'/actual-kernel','stock\n');put(state+'/mode','on\n');put(state+'/kernel-mode','stock\n')
  shell('mkdir -p '+fixture+'/devfreq')
  put(fixture+'/devfreq/governor','simple_ondemand\n');put(fixture+'/devfreq/polling_interval','100\n')
  s=invoke('status');expect(not s['activeKnown'] and s['pendingReboot'],'unknown boot receipt is pending')
  version=dict(line.split('=',1) for line in (ROOT/'magisk-mali-global/module.prop').read_text().splitlines() if '=' in line)['version']
  shell('cat /proc/sys/kernel/random/boot_id > '+current+'/active-boot-id');put(current+'/active-mode','on\n');put(current+'/active-version',version+'\n')
  shell('cat /proc/sys/kernel/random/boot_id > '+current+'/active-dvfs-boot-id');put(current+'/active-dvfs-mode','off\n')
  s=invoke('status');expect(s['activeKnown'] and not s['pendingReboot'],'original pair acknowledged')
  s=invoke('kernel','next');expect(s['kernelRequested']=='next' and s['kernelEffective']=='next' and s['kernelActive']=='stock' and s['pendingReboot'],'save is never live activation')
  s=invoke('set','off');expect(s['kernelRequested']=='next' and s['kernelEffective']=='stock','parent off retains child pair')
  s=invoke('set','on');expect(s['kernelEffective']=='next','parent on restores child selection')
  invoke('set','off');s=invoke('kernel','next');expect(s['requested']=='on','select new pair links userspace on')
  s=invoke('kernel','stock');expect(not s['pendingReboot'],'cancel pending pair change')
  expect(s['dvfsRequested']=='off' and s['dvfsActive']=='off','new response defaults off')
  invoke('set','off');s=invoke('dvfs','on')
  expect(s['requested']=='on' and s['kernelRequested']=='next' and s['dvfsEffective']=='on','response enables both ancestors')
  expect(s['dvfsActive']=='off' and s['pendingReboot'] and s['pollingIntervalMs']==100,'response save never writes live devfreq')
  s=invoke('kernel','stock');expect(s['dvfsRequested']=='on' and s['dvfsEffective']=='off','kernel rollback retains response choice')
  s=invoke('kernel','next');expect(s['dvfsEffective']=='on','pair restores retained response')
  s=invoke('set','off');expect(s['dvfsRequested']=='on' and s['dvfsEffective']=='off','whole off suppresses response')
  invoke('set','on');invoke('dvfs','off');invoke('kernel','stock')
  put(fixture+'/devfreq/polling_interval','50\n')
  s=invoke('status');expect(not s['dvfsSupported'],'unrecognized external polling policy unsupported')
  bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh dvfs on'],capture_output=True);expect(bad.returncode!=0,'cannot replace another polling policy')
  expect(invoke('dvfs','off')['dvfsRequested']=='off','rollback allowed when devfreq unsupported')
  put(fixture+'/devfreq/polling_interval','100\n')
  # Execute the real boot policy only against the fake devfreq directory. Property
  # functions are local stubs so this cannot touch device properties or clocks.
  put(current+'/active-dvfs-plan','on\n');put(state+'/actual-kernel','next\n')
  def boot_policy():
   shell('sh -c '+shlex.quote('getprop(){ echo active; }; resetprop(){ :; }; . '+current+'/dvfs-boot.sh')+' '+current+'/dvfs-boot.sh')
  boot_policy()
  expect(shell('cat '+fixture+'/devfreq/polling_interval').strip()=='20','qualified boot applies 20ms')
  expect(invoke('status')['dvfsActive']=='on','active response requires matching receipt and live value')
  put(fixture+'/devfreq/polling_interval','50\n');expect(invoke('status')['dvfsActive']=='unknown','external changes invalidate active response')
  boot_policy();expect(shell('cat '+fixture+'/devfreq/polling_interval').strip()=='50','boot refuses custom policy')
  put(fixture+'/devfreq/polling_interval','100\n');put(state+'/actual-kernel','stock\n')
  boot_policy();expect(shell('cat '+fixture+'/devfreq/polling_interval').strip()=='100','unqualified pair stays original')
  put(current+'/active-dvfs-plan','off\n');boot_policy()
  expect(invoke('status')['dvfsActive']=='off','off boot acknowledges original policy')
  put(state+'/supported','no\n');s=invoke('status');expect(not s['supported'] and s['kernelEffective']=='stock','unsupported firmware stays original')
  bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh kernel next'],capture_output=True);expect(bad.returncode!=0,'unsupported pair cannot be enabled')
  put(state+'/supported','yes\n');invoke('kernel','next')
  # A completed prior startup must not prevent the next requested boot.
  shell('sh -c '+shlex.quote('. '+current+'/kernel-state.sh; kernel_boot_plan'))
  expect(shell('cat '+state+'/kernel-boot-plan').strip()=='next','boot plans requested pair')
  expect(shell('cat '+state+'/kernel-pending').strip()==shell('cat /proc/sys/kernel/random/boot_id').strip(),'latch written before transition')
  put(state+'/kernel-pending','different-boot\n')
  shell('sh -c '+shlex.quote('. '+current+'/kernel-state.sh; kernel_boot_plan'))
  s=invoke('status');expect(s['kernelRequested']=='stock' and s['recovery']=='interrupted_previous_boot','interrupted startup persists kernel-only rollback')
  expect(s['requested']=='on' and shell('cat '+state+'/kernel-boot-plan').strip()=='stock','rollback retains global userspace')
  put(state+'/kernel-pending','old-failed-attempt\n');invoke('kernel','next')
  expect(shell('test ! -e '+state+'/kernel-pending && echo cleared').strip()=='cleared','explicit retry clears an inactive failed latch')
  shell('touch '+current+'/disable');s=invoke('status');expect(not s['moduleEnabled'] and s['effective']=='off','manager disable suppresses both')
  shell('rm '+current+'/disable')
  # New cold-backend policy; the fake native command only records requests.
  shell('mkdir -p '+current+'/bin '+state+'/boot')
  put(current+'/bin/cold_boot64','#!/system/bin/sh\ncase "$1" in\nverify) test -f '+state+'/prepared;;\napply) echo apply >> '+state+'/calls;test ! -f '+state+'/fail-apply;;\nrestore) echo restore >> '+state+'/calls;test ! -f '+state+'/fail-restore;;\n*) exit 2;;esac\n')
  shell('chmod 0755 '+current+'/bin/cold_boot64')
  bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh cold on'],capture_output=True)
  expect(bad.returncode!=0 and invoke('status')['coldRequested']=='off','cold requires a private verified candidate')
  put(state+'/boot/profile','profile_id '+'a'*64+'\n');put(state+'/prepared','yes\n')
  s=invoke('cold','on');expect(s['coldPrepared'] and s['coldRequested']=='on' and s['kernelRequested']=='next' and s['requested']=='on','cold links userspace and KMD ancestors')
  expect(s['coldActive']=='off' and s['coldEffective']=='on' and s['pendingReboot'],'cold save never changes current backend')
  s=invoke('cold','off');expect(s['coldRequested']=='off' and s['kernelRequested']=='stock','cold off restores original KMD selection')
  put(state+'/fail-apply','yes\n')
  bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh cold on'],capture_output=True)
  s=invoke('status');expect(bad.returncode!=0 and s['coldRequested']=='off' and s['kernelRequested']=='stock','failed cold apply never falls through to legacy handover')
  shell('rm '+state+'/fail-apply');invoke('cold','on');put(state+'/fail-restore','yes\n')
  bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh set off'],capture_output=True)
  expect(bad.returncode!=0 and invoke('status')['requested']=='on','refused restoration preserves parent selection')
  shell('rm '+state+'/fail-restore');s=invoke('set','off');expect(s['coldRequested']=='on' and s['coldEffective']=='off','parent off restores boot and retains cold choice')
  s=invoke('set','on');expect(s['coldEffective']=='on','parent re-enable reapplies selected cold image')
  invoke('kernel','stock');before=shell('cat '+state+'/calls');invoke('set','on')
  expect(shell('cat '+state+'/calls')==before,'parent on with stock KMD never writes a cold boot')
  invoke('cold','off')
  shell('mkdir -p '+current+'/kernel');put(current+'/kernel/rk_mali_next.ko','csf_fence_safe')
  s=invoke('status');expect(s['fenceRequested']=='off' and s['fenceActive']=='off','fence default off')
  s=invoke('fence','on');expect(s['fenceEffective']=='on' and s['coldRequested']=='on' and s['kernelRequested']=='next' and s['requested']=='on','fence links all required ancestors')
  expect(s['fenceActive']=='off' and s['pendingReboot'],'fence save does not apply live')
  put(state+'/actual-kernel','next\n');put(state+'/fence-actual','Y\n');expect(invoke('status')['fenceActive']=='on','fence reads actual kernel flag')
  s=invoke('fence','off');expect(s['fenceActive']=='on' and s['fenceEffective']=='off' and s['pendingReboot'],'fence off waits for reboot')
  put(state+'/fence-actual','N\n');expect(invoke('status')['fenceActive']=='off','fence kernel flag N reports off')
  invoke('fence','on');s=invoke('kernel','stock');expect(s['fenceRequested']=='on' and s['fenceEffective']=='off','fence selection retained under parent off')
  invoke('cold','off');invoke('fence','off');put(state+'/actual-kernel','stock\n')
  put(state+'/fail-apply','yes\n');bad=subprocess.run(adb+['shell','sh '+current+'/webui.sh fence on'],capture_output=True)
  expect(bad.returncode!=0 and invoke('status')['fenceRequested']=='off','failed boot apply never enables fence leaf');shell('rm '+state+'/fail-apply')
  put(staged+'/module.prop','id=rk3588_mali_global\nversion=0.3.1\n')
  for name in ['kernel-state.sh','cold-state.sh','dvfs-state.sh','fence-state.sh','mode-control.sh']:put(staged+'/'+name,shell('cat '+current+'/'+name))
  s=invoke('status');expect(s['staged'] and s['version']=='0.3.1' and s['activeVersion']==version and s['pendingReboot'],'staged update is distinguished from current boot')
  for args in [('fence','on;id'),('fence','on','extra'),('fence','bogus'),('kernel','next;id'),('cold','on;id'),('cold','on','extra'),('dvfs','on;id'),('dvfs','on','extra'),('set','on','extra'),('status','extra'),('unknown',)]:
   result=subprocess.run(adb+['shell','sh '+current+'/webui.sh '+' '.join(shlex.quote(x) for x in args)],capture_output=True)
   expect(result.returncode!=0,'fixed command boundary')
  print(json.dumps({'checks':checks,'android_shell_passed':True,'live_module_modified':False}))
 finally:shell('rm -r '+fixture)
if __name__=='__main__':main()
