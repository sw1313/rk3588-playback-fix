"""Selectively import Rockchip d0e8f558 QMS timing data, not its pointer walks."""
import argparse
import hashlib
from pathlib import Path
import re

PIN = '526b313b9084d22ad1bab12f9c7cd8baff8c00af7ca8d8441c323f7c4f1bd164'
RATES = {2397: 1, 2400: 2, 2500: 3, 2997: 4, 3000: 5, 4795: 6, 4800: 7,
         5000: 8, 5994: 9, 6000: 10, 10000: 11, 11988: 12, 12000: 13}
VICS = {'720p60': 4, '720p120': 47, '1080p60': 16, '1080p120': 63, '2160p60': 97}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--patch', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    a = p.parse_args()
    data = a.patch.read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN:
        raise RuntimeError('Upstream patch SHA256 mismatch')
    source = '\n'.join(line[1:] for line in data.decode().splitlines() if line.startswith('+') and not line.startswith('+++'))
    rows = []
    for name, body in re.findall(r'static const struct mvrr_const_val const_hdmi(\w+) = \{(.*?)\n\};', source, re.S):
        group, rate = name.rsplit('_', 1)
        def field(key, default=0):
            found = re.search(r'\.' + key + r'\s*=\s*(\d+)', body)
            return int(found[1]) if found else default
        vtotal, bits = field('vtotal_fixed'), field('bit_len')
        found = re.search(r'\.frac_array\s*=\s*\{(.*?)\}', body, re.S)
        values = re.findall(r'0x[0-9a-f]+', found[1]) if found else []
        if not vtotal or bits > 128 or len(values) * 8 != bits:
            raise RuntimeError('Invalid upstream data ' + name)
        # Local corrections identified by exact-cycle rational-rate checks.
        # The 720p120/59.94 table has the same 1501.5 target and correct bits.
        if name == '720p60_2997':
            if (vtotal, bits, values[0]) != (1501, 56, '0x1f'):
                raise RuntimeError('Unexpected source for 720p table correction')
            values[0] = '0x0f'
        # 1125*120/(48000/1001) = 2815.3125, not 2812.3125.
        if name == '1080p120_4795':
            if (vtotal, bits) != (2812, 48):
                raise RuntimeError('Unexpected source for 1080p table correction')
            vtotal = 2815
        rows.append((VICS[group], RATES[int(rate)], vtotal, bits, values))
    if len(rows) != 56 or len({(r[0], r[1]) for r in rows}) != len(rows):
        raise RuntimeError('Unexpected upstream table coverage: ' + str(len(rows)))
    lines = ['// SPDX-License-Identifier: GPL-2.0-only',
             '/* Timing data from Rockchip d0e8f558bc58984f8f4508133143cc9ca77c8b0d.',
             ' * Copyright (C) Rockchip Electronics Co., Ltd.; Algea Cao.',
             ' * Generated by tools/qms/import_tables.py. VIC102 shares VIC97 data.',
             ' * Bounded keyed lookup replaces the upstream sentinel pointer walk.',
             ' * Local exact-rate fixes: VIC4/TFR4 first byte 1f->0f;',
             ' * VIC63/TFR6 integer vtotal 2812->2815. See UPSTREAM.json. */',
             'static const struct rkqms_timing rkqms_timings[] = {']
    for vic, rate, vtotal, bits, values in rows:
        lines.append('    { %d, %d, %d, %d, { %s } },' % (vic, rate, vtotal, bits, ', '.join(values) or '0'))
    lines += ['};', '']
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text('\n'.join(lines), encoding='utf8', newline='\n')
    print('Imported %d bounded timing records' % len(rows))


if __name__ == '__main__':
    main()
